def blank(text):
    return "".join("\n" if ch == "\n" else " " for ch in text)


def strip_noise(text, comments=None):
    """Blank out comments, strings and char literals (keeps newlines so line numbers stay valid).
    When 'comments' is a list, every comment is appended to it as (line, text)."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        two = text[i:i + 2]
        if two == "//":
            end = text.find("\n", i)
            end = n if end == -1 else end
            if comments is not None:
                comments.append((text.count("\n", 0, i) + 1, text[i:end]))
            out.append(" " * (end - i))
            i = end
        elif two == "/*":
            end = text.find("*/", i + 2)
            end = n if end == -1 else end + 2
            if comments is not None:
                comments.append((text.count("\n", 0, i) + 1, text[i:end]))
            out.append(blank(text[i:end]))
            i = end
        elif text.startswith('"""', i):
            end = text.find('"""', i + 3)
            end = n if end == -1 else end + 3
            out.append(blank(text[i:end]))
            i = end
        elif c == '"' or (c in "@$" and text[i:i + 3].lstrip("@$").startswith('"') and '"' in text[i:i + 3]):
            j = i
            verbatim = False
            while j < n and text[j] in "@$":
                verbatim = verbatim or text[j] == "@"
                j += 1
            j += 1
            while j < n:
                if verbatim and text[j:j + 2] == '""':
                    j += 2
                    continue
                if not verbatim and text[j] == "\\":
                    j += 2
                    continue
                if text[j] == '"':
                    j += 1
                    break
                j += 1
            out.append(blank(text[i:j]))
            i = j
        elif c == "'":
            j = i + 1
            while j < n and text[j] != "'":
                j += 2 if text[j] == "\\" else 1
            j += 1
            out.append(" " * (j - i))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


ENGLISH_MARKERS = {"the", "returns", "return", "gets", "sets", "creates", "if", "when", "this", "that",
                   "with", "is", "are", "will", "should", "and", "of", "to"}


def english_comment_warnings(path):
    """NON-BLOCKING heuristic: comments (// and /// XML docs) must be written in Spanish.
    A comment is reported when it has 2 or more common English words (the, returns, gets, if, when ...)."""
    with open(path, encoding="utf-8-sig", errors="replace") as handle:
        text = handle.read()
    comments = []
    strip_noise(text, comments)
    warnings = []
    for line_number, comment in comments:
        plain = re.sub(r"<[^>]+>", " ", comment)
        words = set(re.findall(r"[a-z]+", plain.lower()))
        hits = sorted(words & ENGLISH_MARKERS)
        if len(hits) >= 2:
            warnings.append((line_number, ", ".join(hits)))
    return warnings


def is_spanish(part, allow):
    word = part.lower()
    if word in allow or len(word) < 3:
        return False
    if word in SPANISH_WORDS:
        return True
    for suffix in ("es", "s"):
        if word.endswith(suffix) and word[: -len(suffix)] in SPANISH_WORDS and word[: -len(suffix)] not in allow:
            return True
    return False


def check_file(path, allow):
    with open(path, encoding="utf-8-sig", errors="replace") as handle:
        text = handle.read()
    findings = []
    seen = set()
    for line_number, line in enumerate(strip_noise(text).split("\n"), start=1):
        for match in IDENTIFIER.finditer(line):
            identifier = match.group(0)
            if (line_number, identifier) in seen:
                continue
            seen.add((line_number, identifier))
            if not identifier.isascii():
                findings.append((line_number, identifier, "non-ASCII letter"))
                continue
            for part in WORD_PARTS.findall(identifier.replace("_", " ")):
                if is_spanish(part, allow):
                    findings.append((line_number, identifier, "Spanish word \'%s\'" % part.lower()))
                    break
    return findings


def load_allowlist(extra):
    allow = set(extra)
    allow_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "english-allowlist.txt")
    if os.path.exists(allow_file):
        with open(allow_file, encoding="utf-8") as handle:
            for raw in handle:
                entry = raw.split("#", 1)[0].strip().lower()
                if entry:
                    allow.add(entry)
    return allow


def main(argv):
    args = argv[1:]
    extra = []
    if "--allow" in args:
        index = args.index("--allow")
        extra = [w.strip().lower() for w in args[index + 1].split(",") if w.strip()]
        del args[index:index + 2]
    allow = load_allowlist(extra)
    roots = args or ["."]
    checked, violations, warned = 0, 0, 0
    for root in roots:
        for current, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d.lower() not in IGNORED_DIRS]
            for file_name in sorted(files):
                lower = file_name.lower()
                if not lower.endswith(".cs") or lower.endswith(IGNORED_SUFFIXES):
                    continue
                path = os.path.join(current, file_name)
                checked += 1
                for line_number, hits in english_comment_warnings(path):
                    warned += 1
                    print("WARN %s:%d: comentario en inglés (los comentarios van en español): %s" % (os.path.relpath(path), line_number, hits))
                for line_number, identifier, reason in check_file(path, allow):
                    violations += 1
                    print("%s:%d:%s (%s)" % (os.path.relpath(path), line_number, identifier, reason))
    print("check-english-identifiers: %d files checked, %d violations, %d warnings (comments in English, non-blocking)" % (checked, violations, warned))
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
